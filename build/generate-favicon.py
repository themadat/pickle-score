#!/usr/bin/env python3
"""
generate-favicon.py
-------------------
Combine assets/icons/pickle-score-{light,dark}.svg into a single
assets/icons/favicon.svg that swaps fills via @media (prefers-color-scheme).

The two source SVGs are expected to share identical geometry and differ only
in their fill colors. The script assigns generated classes in fill order, so
future icon art can add or remove filled shapes without changing this file.
"""

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
LIGHT = REPO_ROOT / "assets" / "icons" / "pickle-score-light.svg"
DARK = REPO_ROOT / "assets" / "icons" / "pickle-score-dark.svg"
OUT = REPO_ROOT / "assets" / "icons" / "favicon.svg"

FILL_RE = re.compile(r'fill="([^"]+)"')


def extract_fills(path: Path) -> list[str]:
    text = path.read_text()
    fills = FILL_RE.findall(text)
    if not fills:
        sys.exit(f"Error: {path.name} has no fill attributes to theme.")
    return fills


def main() -> None:
    for svg in (LIGHT, DARK):
        if not svg.exists():
            sys.exit(f"Error: missing source SVG: {svg}")

    light_fills = extract_fills(LIGHT)
    dark_fills = extract_fills(DARK)
    if len(light_fills) != len(dark_fills):
        sys.exit(
            f"Error: light/dark fill counts differ "
            f"({len(light_fills)} vs {len(dark_fills)})."
        )
    classes = [f"icon-fill-{i + 1}" for i in range(len(light_fills))]
    text = LIGHT.read_text()
    idx = [0]

    def sub(_match: re.Match[str]) -> str:
        cls = classes[idx[0]]
        idx[0] += 1
        return f'class="{cls}"'

    body = FILL_RE.sub(sub, text)

    style_lines = ["  <style>"]
    for cls, color in zip(classes, light_fills):
        style_lines.append(f"    .{cls} {{ fill: {color}; }}")
    style_lines.append("    @media (prefers-color-scheme: dark) {")
    for cls, color in zip(classes, dark_fills):
        style_lines.append(f"      .{cls} {{ fill: {color}; }}")
    style_lines.append("    }")
    style_lines.append("  </style>")
    style = "\n".join(style_lines)

    body = re.sub(r"<!DOCTYPE[^>]*>\s*", "", body, count=1)
    body, count = re.subn(r"(<svg[^>]*>)", r"\1\n" + style, body, count=1)
    if count != 1:
        sys.exit("Error: couldn't locate <svg> opening tag.")

    header_comment = (
        "<!-- Generated by build/generate-favicon.py from "
        "assets/icons/pickle-score-{light,dark}.svg. Do not edit by hand. -->"
    )
    body, count = re.subn(
        r"(<\?xml[^>]*\?>)", r"\1\n" + header_comment, body, count=1
    )
    if count != 1:
        body = header_comment + "\n" + body

    OUT.write_text(body)
    print("  favicon.svg                      generated (light + dark @media)")


if __name__ == "__main__":
    main()
